import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { AssistTools, ASSIST_BINDING, validateAssist } from "../src/assist-tools.mjs";

const bundle = { prompt: "HA native context", tools: [{ name: "intent__HassTurnOn", description: "Turn on",
  parameters: { type: "object", properties: { name: { type: "string" } }, required: ["name"] } }] };
const request = { request: { tool_name: "intent__HassTurnOn", tool_args: { name: "Fixture" } } };
function fixture(timeoutMs) {
  const bridge = new AssistTools({ timeoutMs });
  const controller = new AbortController();
  const events = [];
  const owner = { agentId: "voice", sessionKey: "agent:voice:test", sessionId: "incarnation", runId: "run", principal: "client", requestId: "request" };
  const lease = bridge.open({ ...owner, bundle, signal: controller.signal, emit: async (event) => events.push(event) });
  const ctx = { ...owner, toolBindings: { [ASSIST_BINDING]: lease.token }, assertInvocationCurrent() {} };
  return { bridge, controller, events, owner, lease, ctx, tool: bridge.factory(ctx) };
}

test("native schemas are carried unchanged; bindings isolate agent, session, incarnation and turn", async () => {
  const { bridge, ctx, tool, lease, owner } = fixture();
  assert.deepEqual(tool.parameters.properties.request.anyOf[0].properties.tool_args, bundle.tools[0].parameters);
  for (const field of ["agentId", "sessionKey", "sessionId"])
    assert.equal(bridge.factory({ ...ctx, [field]: "other" }), null);
  assert.equal(bridge.factory({ ...ctx, toolBindings: {} }), null);
  assert.equal(bridge.prompt({}, { ...owner, runId: "other" }), undefined);
  assert.equal(bridge.prompt({}, { ...owner, sessionId: "other" }), undefined);
  assert.match(bridge.prompt({}, owner).appendSystemContext, /FIRST/);
  lease.close();
  assert.equal(bridge.factory(ctx), null);
  await assert.rejects(tool.execute("x", request), /assist_turn_closed/);
});

test("exact schema discovery is read-only, isolated, immutable, and preserves HA argument types", async () => {
  const { bridge, tool, lease, events, controller } = fixture();
  const described = await tool.execute("schema", { describe: "intent__HassTurnOn" });
  assert.deepEqual(JSON.parse(described.content[0].text), bundle.tools[0]);
  described.details.parameters.properties.name.type = "number";
  assert.deepEqual((await tool.execute("schema", { describe: "intent__HassTurnOn" })).details, bundle.tools[0]);
  for (const args of [{}, { describe: "admin" }, { describe: "intent__HassTurnOn", ...request },
    { describe: "intent__HassTurnOn", extra: true }])
    await assert.rejects(tool.execute("invalid", args), /invalid_assist_call/);
  assert.equal(events.length, 0, "schema reads must not emit HA execution events");
  controller.abort();
  await assert.rejects(tool.execute("schema", { describe: "intent__HassTurnOn" }), /assist_turn_closed/);
  lease.close();
  assert.equal(bridge.factory({}), null);
});

test("real HA 2026.10.4 schema discovery distinguishes intent arrays from live-context unions", async () => {
  // Generated by the companion tests/export_assist_schema.py with synthetic entities.
  const native = JSON.parse(await readFile(new URL("./fixtures/ha-assist-schema-2026.10.4.json", import.meta.url), "utf8"));
  const bridge = new AssistTools();
  const owner = { agentId: "fixture", sessionKey: "fixture", sessionId: "incarnation", runId: "turn" };
  let events = 0;
  const lease = bridge.open({ ...owner, bundle: native, signal: new AbortController().signal,
    emit: async () => { events++; } });
  const tool = bridge.factory({ ...owner, toolBindings: { [ASSIST_BINDING]: lease.token } });
  for (const expected of native.tools) {
    const result = await tool.execute("schema", { describe: expected.name });
    assert.deepEqual(JSON.parse(result.content[0].text), expected);
  }
  const off = (await tool.execute("schema", { describe: "intent__HassTurnOff" })).details;
  assert.equal(off.parameters.properties.domain.type, "array");
  assert.equal(off.parameters.properties.domain.items.type, "string");
  const live = (await tool.execute("schema", { describe: "homeassistant__GetLiveContext" })).details;
  assert.deepEqual(live.parameters.properties.domain.anyOf.map((variant) => variant.type), ["string", "array"]);
  assert.equal(events, 0);
  lease.close();
  await assert.rejects(tool.execute("schema", { describe: off.name }), /assist_turn_closed/);
});

test("call result requires owning client and request; identical result retry never redispatches", async () => {
  const { bridge, events, tool, lease } = fixture();
  const pending = tool.execute("x", request);
  await Promise.resolve();
  const value = { call_id: events[0].call_id, data: { success: true }, error: false };
  assert.throws(() => bridge.result("other", "request", value), /assist_call_not_found/);
  assert.throws(() => bridge.result("client", "other", value), /assist_call_not_found/);
  bridge.claim("client", "request", value.call_id);
  assert.throws(() => bridge.claim("client", "request", value.call_id), /assist_call_closed/);
  bridge.result("client", "request", value);
  assert.deepEqual((await pending).details, { success: true });
  assert.deepEqual(bridge.result("client", "request", value), { accepted: true });
  assert.throws(() => bridge.result("client", "request", { ...value, error: true }), /assist_result_conflict/);
  assert.equal(events.length, 1);
  lease.close();
});

test("unknown tools, malformed arguments, cancellation and late results fail closed", async () => {
  const { bridge, tool, controller, events, lease } = fixture();
  await assert.rejects(tool.execute("x", { request: { tool_name: "admin", tool_args: {} } }), /invalid_assist_call/);
  assert.equal(events.length, 0);
  const pending = tool.execute("x", request);
  controller.abort();
  await assert.rejects(pending, /assist_outcome_unknown/);
  assert.throws(() => bridge.result("client", "request", { call_id: events[0].call_id, data: {}, error: false }), /assist_call_not_found/);
  lease.close();
});

test("bounded timeout does not retry an uncertain HA action", async () => {
  const { bridge, tool, events, lease } = fixture(5);
  const pending = tool.execute("x", request);
  bridge.claim("client", "request", events[0].call_id);
  await assert.rejects(pending, /assist_outcome_unknown/);
  assert.equal(events.length, 1);
  assert.throws(() => bridge.result("client", "request", { call_id: events[0].call_id, data: {}, error: false }), /assist_call_closed/);
  lease.close();
});

test("reject duplicate names and oversized native context instead of truncating policy", () => {
  assert.throws(() => validateAssist({ ...bundle, tools: [...bundle.tools, ...bundle.tools] }), /invalid_assist_tool/);
  assert.throws(() => validateAssist({ ...bundle, prompt: "x".repeat(131073) }), /invalid_assist_bundle/);
});
